-- SteveCraft: list only eligible 90-day-old files in the PRIVATE design-references bucket.
-- Run in SteveCraft Supabase SQL Editor. Read-only; this SQL DOES NOT delete images.
-- Only service_role can invoke this RPC; the browser/anon/authenticated roles cannot.
create or replace function public.list_expired_design_references(p_limit integer default 100)
returns table(object_path text, uploaded_at timestamptz)
language sql
security definer
set search_path = ''
as $function$
  select o.name::text, o.created_at
  from storage.objects as o
  where o.bucket_id = 'design-references'
    and o.created_at < now() - interval '90 days'
    -- Only files generated by SteveCraft's reference upload function.
    and o.name ~ '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}/[1-3]\\.(jpg|png|webp)$'
  order by o.created_at asc, o.name asc
  limit least(greatest(coalesce(p_limit, 100), 1), 100);
$function$;

revoke all on function public.list_expired_design_references(integer) from public, anon, authenticated;
grant execute on function public.list_expired_design_references(integer) to service_role;

-- The RPC is discovery only. Permanent deletion MUST use Supabase Storage API.
